    // MARK: iCal 解析

    @Test("解析 iCal 课程事件")
    func testParseICal() {
        let ical = """
        BEGIN:VCALENDAR
        BEGIN:VEVENT
        SUMMARY:高等数学
        LOCATION:综教A101
        DESCRIPTION:王老师 | 1-16周
        DTSTART;TZID=Asia/Shanghai:20250901T080000
        DTEND;TZID=Asia/Shanghai:20250901T094000
        END:VEVENT
        END:VCALENDAR
        """
        let (events, firstDay) = NetworkManager.shared.parseiCal(ical)
        #expect(events.count == 1)
        guard let e = events.first else { return }
        #expect(e.summary == "高等数学")
        #expect(e.location == "综教A101")
        #expect(e.teacher == "王老师")
        #expect(e.startSection == 1)   // 8:00 → 第1节
        #expect(e.duration >= 2)
        // 学期第一天是事件最早日期所在周的周一
        let cal = Calendar.current
        #expect(cal.component(.weekday, from: firstDay) == 2)  // 周一
    }

